#!/usr/bin/env node
/**
 * Copies the MosBot brand assets this repository renders from the mobile
 * project into src/renderer/assets/brand and records provenance in
 * src/renderer/assets/brand/provenance.json.
 *
 * Source: ~/dev/MosBot, pinned to BRAND_SHA. Re-run after bumping the pin, then
 * review the copied files and the provenance diff together.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const BRAND_SHA = '3c118c4';
const SOURCE_ROOT = path.join(os.homedir(), 'dev', 'MosBot');
const TARGET_ROOT = path.resolve(import.meta.dirname, '..', 'src', 'renderer', 'assets', 'brand');

const ASSETS = [
  { from: 'AppScope/resources/base/media/app_icon.png', to: 'app-icon.png' },
  { from: 'entry/src/main/resources/base/media/empty_chat_bubbles.svg', to: 'empty-chat.svg' },
  {
    from: 'entry/src/main/resources/base/media/mosbot_wordmark_letters.svg',
    to: 'wordmark-letters.svg',
  },
  { from: 'entry/src/main/resources/base/media/mosbot_wordmark_eyes.svg', to: 'wordmark-eyes.svg' },
  { from: 'licenses/hermes-desktop-bots-LICENSE', to: 'hermes-desktop-bots-LICENSE' },
  { from: 'LICENSE', to: 'MosBot-LICENSE' },
];

function sha256Of(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

/** Collects the `d` attributes of every <path> plus the viewBox of an SVG file. */
function parseArtwork(file) {
  const text = readFileSync(file, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(text)?.[1] ?? '0 0 32 32';
  const paths = Array.from(text.matchAll(/<path\b[^>]*\bd="([^"]+)"/g), (match) => match[1]).filter(
    (d) => typeof d === 'string' && d.length > 0,
  );
  return { viewBox, paths };
}

/**
 * The renderer draws the wordmark and the empty-chat mark as inline SVG: CSS
 * masks over `?url` imports are dropped in the packaged file:// page, and inline
 * paths keep them themeable and CSP-friendly.
 */
function writeArtworkModule(targetRoot) {
  const letters = parseArtwork(path.join(SOURCE_ROOT, ASSETS[2].from));
  const eyes = parseArtwork(path.join(SOURCE_ROOT, ASSETS[3].from));
  const emptyChat = parseArtwork(path.join(SOURCE_ROOT, ASSETS[1].from));
  const literal = (values) =>
    `[\n${values.map((value) => `  ${JSON.stringify(value)},`).join('\n')}\n]`;
  const body = [
    '// Generated by scripts/sync-brand-assets.mjs from MosBot@' +
      BRAND_SHA +
      '; do not edit by hand.',
    `export const WORDMARK_VIEW_BOX = ${JSON.stringify(letters.viewBox)};`,
    `export const WORDMARK_LETTER_PATHS: readonly string[] = ${literal(letters.paths)};`,
    `export const WORDMARK_EYE_PATHS: readonly string[] = ${literal(eyes.paths)};`,
    `export const EMPTY_CHAT_VIEW_BOX = ${JSON.stringify(emptyChat.viewBox)};`,
    'export const EMPTY_CHAT_STROKE_WIDTH = 1.8;',
    `export const EMPTY_CHAT_PATHS: readonly string[] = ${literal(emptyChat.paths)};`,
    '',
  ].join('\n');
  writeFileSync(path.join(targetRoot, 'artwork.ts'), body);
}

function main() {
  const head = execFileSync('git', ['-C', SOURCE_ROOT, 'rev-parse', '--short=7', 'HEAD'], {
    encoding: 'utf8',
  }).trim();
  if (head !== BRAND_SHA) {
    throw new Error(`MosBot checkout is at ${head}, expected ${BRAND_SHA}`);
  }

  mkdirSync(TARGET_ROOT, { recursive: true });
  const entries = [];
  for (const asset of ASSETS) {
    const source = path.join(SOURCE_ROOT, asset.from);
    const target = path.join(TARGET_ROOT, asset.to);
    copyFileSync(source, target);
    entries.push({
      file: asset.to,
      source: `MosBot@${BRAND_SHA}:${asset.from}`,
      sha256: sha256Of(target),
    });
  }

  writeArtworkModule(TARGET_ROOT);
  writeFileSync(
    path.join(TARGET_ROOT, 'provenance.json'),
    `${JSON.stringify({ pinnedSha: BRAND_SHA, command: 'pnpm assets:sync', assets: entries }, null, 2)}\n`,
  );
  console.warn(`Copied ${entries.length} brand assets from MosBot@${BRAND_SHA}`);
}

main();
